    fpath = base / f"src/renderer/src/locales/{lang}/settings.json"
    data = json.loads(fpath.read_text(encoding="utf-8"))
    if "mcp" not in data:
        data["mcp"] = mcp_data
    if "tabs" in data and "mcp" not in data["tabs"]:
        data["tabs"]["mcp"] = tabs_data
    fpath.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"{lang}: OK")
